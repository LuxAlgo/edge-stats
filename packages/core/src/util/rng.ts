/*
  Deterministic PRNG for the synthetic adapter and benchmarks. Same seed,
  same machine or not — same bars, same goldens.
*/

export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Standard normal via Box–Muller; consumes exactly two draws per call. */
export function gaussian(rng: Rng): number {
  const u = Math.max(rng(), 1e-12);
  const v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

export function pick<T>(rng: Rng, items: readonly T[]): T {
  const i = Math.min(items.length - 1, Math.floor(rng() * items.length));
  const item = items[i];
  if (item === undefined) throw new Error("pick from empty list");
  return item;
}
